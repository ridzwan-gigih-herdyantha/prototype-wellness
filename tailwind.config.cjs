/**
 * Tailwind cannot apply an opacity modifier to a color whose value is a bare
 * `var(...)`, because it has nowhere to inject the alpha. It silently emits no
 * rule at all, so `bg-background/60` and friends rendered fully transparent.
 * That accounted for ~1,470 utilities across the app.
 *
 * withAlpha() wraps each themed token so the modifier composites the token
 * against transparent instead. Un-suffixed classes are unchanged: the alpha
 * defaults to 1, which resolves to 100% of the original token value. Tokens
 * that already carry their own alpha (the surface and border scales) keep it,
 * since the mix is relative to the token rather than replacing it.
 */
const withAlpha = (token) =>
  `color-mix(in srgb, ${token} calc(<alpha-value> * 100%), transparent)`;

